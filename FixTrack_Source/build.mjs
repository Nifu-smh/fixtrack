import {readFile,writeFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {spawnSync} from 'node:child_process';
const root=path.dirname(fileURLToPath(import.meta.url));
const read=name=>readFile(path.join(root,name),'utf8');
const [html,css,domain,data,app,ico]=await Promise.all(['index.html','styles.css','domain.js','data.js','app.js','favicon.svg'].map(read));
const removeExports=s=>s.replaceAll(/^export /gm,'');
let source=app.replace(/^import .*\r?\n/gm,'');
source=source.replaceAll('location.pathname',"(location.hash.slice(1).split('?')[0] || '/')");
source=source.replaceAll('new URLSearchParams(location.search)',"new URLSearchParams(location.hash.split('?')[1] || '')");
source=source.replace("history.pushState({},'',url)","history.pushState({},'','#'+url)");
source=source.replace("history.replaceState({},'',(location.hash.slice(1).split('?')[0] || '/'))", "history.replaceState({},'','#'+(location.hash.slice(1).split('?')[0] || '/'))");
source=source.replace("navigate(link.getAttribute('href'))", "navigate(link.getAttribute('href').replace(/^#/,''))");
source=source.replace("document.querySelector('#app').innerHTML=content;bindInputs();", "document.querySelector('#app').innerHTML=content;document.querySelectorAll('a[data-nav]').forEach(el=>{const href=el.getAttribute('href');if(href.startsWith('/'))el.setAttribute('href','#'+href);});bindInputs();");
source=source.replace("window.addEventListener('popstate'", "window.addEventListener('hashchange'");
source="const e=escapeHtml;\n"+source;
const bundle=removeExports(domain)+'\n'+removeExports(data)+'\n'+source;
const syntax=spawnSync(process.execPath,['--input-type=module','--check'],{input:bundle,encoding:'utf8'});
if(syntax.status!==0)throw new Error(syntax.stderr||'Bundled module syntax check failed');
const output=html.replace('<link rel="icon" href="/favicon.svg" type="image/svg+xml">',`<link rel="icon" href="data:image/svg+xml,${encodeURIComponent(ico)}" type="image/svg+xml">`).replace('<link rel="stylesheet" href="/styles.css">','<style>'+css+'</style>').replace('<script type="module" src="/app.js"></script>','<script type="module">'+bundle.replaceAll('</script','<\\/script')+'</script>');
await writeFile(path.join(root,'FixTrack.html'),output,'utf8');
console.log('Built FixTrack.html — self-contained, offline, and ready to open.');
